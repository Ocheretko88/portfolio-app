// Generates src/environments/runtime-config.ts at install/serve/build time so
// build-environment values reach the app without being committed. Same shape
// and lifecycle as generate-version.mjs (postinstall / prestart / prebuild),
// and the output file is likewise git-ignored.
//
// Today it carries one value:
//   gymWriteToken -> GYM_WRITE_TOKEN, the shared secret the API requires on
//                    mutating /gym routes (ADR-0008).
//
// NOTE, and this is the whole point of ADR-0008's caveat: whatever lands here
// is compiled into the bundle and is readable by anyone who opens the deployed
// JavaScript. This is not a place for a real secret. The gym write token is
// deliberately a low-value, rotatable, anti-drive-by credential — it stops a
// stranger who finds the URL, not a determined reader. Do not add anything here
// that would actually hurt if published.
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const gymWriteToken = process.env.GYM_WRITE_TOKEN ?? '';

// The value is interpolated into a single-quoted TS string literal below.
// Escape backslashes first, then quotes — the reverse order would double-escape
// the backslashes this step itself introduces. Prettier formats this file with
// single quotes and format:check covers src/**, so JSON.stringify (double
// quotes) is not an option.
const asTsLiteral = gymWriteToken.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

const body = `// AUTO-GENERATED by scripts/generate-runtime-config.mjs — do not edit, do not commit.
// Regenerated on every install, serve (prestart) and build (prebuild).
// Values come from the build environment; see ADR-0008 for why the gym write
// token is safe to ship in the bundle and what it does and does not protect.
export const RUNTIME_CONFIG = {
  gymWriteToken: '${asTsLiteral}',
} as const;
`;

const target = resolve(root, 'src/environments/runtime-config.ts');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, body);
console.log(
  `[runtime-config] gymWriteToken ${gymWriteToken ? 'set' : 'EMPTY — gym writes will 401'}`,
);
